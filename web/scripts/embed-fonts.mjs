// Embeds the card fonts (OFL, from @fontsource) as base64 so the Indulgence
// NFT image renders correctly in wallets and marketplaces, which load SVGs as
// plain images and cannot fetch web fonts. Runs before dev and build.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const font = (pkg, file) => readFileSync(join(root, "node_modules/@fontsource", pkg, "files", file)).toString("base64");

const faces = [
  ["CardBlackletter", font("unifrakturmaguntia", "unifrakturmaguntia-latin-400-normal.woff2"), "normal"],
  ["CardFell", font("im-fell-english", "im-fell-english-latin-400-normal.woff2"), "normal"],
  ["CardFell", font("im-fell-english", "im-fell-english-latin-400-italic.woff2"), "italic"],
  ["CardFellSC", font("im-fell-english-sc", "im-fell-english-sc-latin-400-normal.woff2"), "normal"],
];
const css = faces
  .map(([name, b64, style]) => `@font-face{font-family:${name};font-style:${style};src:url(data:font/woff2;base64,${b64}) format("woff2")}`)
  .join("");

writeFileSync(
  join(root, "src/lib/card-fonts.generated.ts"),
  `// Generated by scripts/embed-fonts.mjs. Do not edit.\nexport const CARD_FONT_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`card fonts embedded (${Math.round(css.length / 1024)} KB)`);
